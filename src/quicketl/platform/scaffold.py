"""Generate and update platform projects from templates with Copier.

Templates live in the quicketl git repo under `templates/<warehouse>-<orchestrator>/`
and are versioned by quicketl's release tags. A root `copier.yml` picks the
template from the spec, so one tag covers every template.
See docs/adr/0011-copier-template-layout.md.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any

from quicketl._version import __version__

if TYPE_CHECKING:
    from pathlib import Path

    from quicketl.platform.spec import PlatformSpec

TEMPLATE_SOURCE = "https://github.com/ameijin/quicketl.git"
"""Git repo the templates are pulled from."""

ANSWERS_FILE = ".copier-answers.yml"
"""File in a generated project that records the template and version used."""

AVAILABLE_TEMPLATES = frozenset({"snowflake-airflow"})
"""Templates that exist, named `<warehouse>-<orchestrator>`."""


class ScaffoldError(Exception):
    """Raised when a project cannot be generated or updated."""


def template_name(spec: PlatformSpec) -> str:
    """Return the template a spec selects, such as `snowflake-airflow`."""
    return f"{spec.warehouse.type}-{spec.orchestrator.type}"


def default_ref() -> str:
    """Return the git tag matching the installed quicketl, such as `v2.0.0`."""
    return f"v{__version__}"


def _check_template(spec: PlatformSpec) -> None:
    name = template_name(spec)
    if name not in AVAILABLE_TEMPLATES:
        available = ", ".join(sorted(AVAILABLE_TEMPLATES))
        raise ScaffoldError(f"No template yet for {name}. Available templates: {available}")


def _answers(spec: PlatformSpec) -> dict[str, Any]:
    return {"spec": spec.model_dump(mode="json")}


def _run(action: str, call: Any) -> None:
    """Run a Copier call and turn its errors into ScaffoldError."""
    from copier.errors import CopierError
    from plumbum.commands.processes import ProcessExecutionError

    try:
        call()
    except CopierError as e:
        raise ScaffoldError(f"{action} failed: {e}") from e
    except ProcessExecutionError as e:
        detail = (e.stderr or str(e)).strip()
        raise ScaffoldError(f"{action} failed while running git: {detail}") from e
    except ValueError as e:
        # Copier raises a plain ValueError for a --ref that is not in the repo.
        hint = " Check that --ref is a tag in the repo." if "revision" in str(e) else ""
        raise ScaffoldError(f"{action} failed: {e}.{hint}") from e


def scaffold(
    spec: PlatformSpec,
    dest: Path,
    *,
    template: str = TEMPLATE_SOURCE,
    ref: str | None = None,
) -> None:
    """Generate a new platform project from a spec.

    Args:
        spec: A validated platform spec.
        dest: Folder to generate into. It may already hold platform.yml.
        template: Git URL or local path of the template repo.
        ref: Git tag or commit to use. Defaults to the installed quicketl version.

    Raises:
        ScaffoldError: If no template matches the spec, the folder was already
            scaffolded, or Copier fails.
    """
    _check_template(spec)
    if (dest / ANSWERS_FILE).exists():
        raise ScaffoldError(
            f"{dest} was already generated (it has {ANSWERS_FILE}). "
            "Use `quicketl platform update` instead."
        )

    import copier

    _run(
        "Scaffold",
        lambda: copier.run_copy(
            template,
            dest,
            data=_answers(spec),
            defaults=True,
            vcs_ref=ref or default_ref(),
            unsafe=False,
            quiet=True,
        ),
    )


def update(spec: PlatformSpec, dest: Path, *, ref: str | None = None) -> None:
    """Apply spec and template changes to a generated project.

    The project must be a git repo with no uncommitted changes. Where a
    template change clashes with your own edits, Copier leaves inline
    conflict markers for you to resolve.

    Args:
        spec: The validated spec, usually the project's own platform.yml.
        dest: The generated project folder.
        ref: Git tag or commit to update to. Defaults to the installed quicketl version.

    Raises:
        ScaffoldError: If the folder was not generated by scaffold, no template
            matches the spec, or Copier fails.
    """
    _check_template(spec)
    # Copier compares this path with git's resolved repo root, so symlinks
    # in it (such as /var -> /private/var on macOS) must be resolved first.
    dest = dest.resolve()
    if not (dest / ANSWERS_FILE).exists():
        raise ScaffoldError(
            f"{dest} has no {ANSWERS_FILE}, so it was not generated by "
            "`quicketl platform scaffold`."
        )

    import copier

    _run(
        "Update",
        lambda: copier.run_update(
            dest,
            data=_answers(spec),
            defaults=True,
            overwrite=True,
            vcs_ref=ref or default_ref(),
            unsafe=False,
            quiet=True,
        ),
    )
